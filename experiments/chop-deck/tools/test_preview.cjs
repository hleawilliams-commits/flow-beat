const { chromium } = require('playwright');
const fs=require('fs'),path=require('path'),assert=require('assert');
const preview=process.argv[2], output=process.argv[3];
if(!preview||!output)throw new Error('Usage: node test_preview.cjs /path/to/rendered-preview.html /path/to/private-results');
fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE});
 const page=await browser.newPage({viewport:{width:800,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{const Native=window.AudioContext;window.AudioContext=class extends Native{constructor(...a){super(...a);window.__testAudio=this;const an=this.createAnalyser();an.fftSize=2048;window.__testAnalyser=an;an.connect(this.destination);const original=AudioNode.prototype.connect;AudioNode.prototype.connect=function(dest,...rest){return original.call(this,dest===window.__testAudio.destination&&this!==an?an:dest,...rest);};}};});
 await page.goto('file://'+path.resolve(preview));
 const frame=page.frameLocator('iframe');
 await frame.locator('#flow-chop-demo').waitFor();
 const f=page.frames().find(f=>f!==page.mainFrame());
 const energy=()=>f.evaluate(()=>{const a=window.__testAnalyser;if(!a)return 0;const d=new Float32Array(a.fftSize);a.getFloatTimeDomainData(d);return Math.max(...d.map(Math.abs));});
 await frame.locator('#chop-beat').click();
 await frame.locator('#chop-status').filter({hasText:'Beat playing'}).waitFor();
 await page.waitForTimeout(400);
 const backingPeak=await energy();assert(backingPeak>.001,'Beat produces audio');
 await frame.locator('[data-pad="0"]').click();
 await page.waitForTimeout(100);
 assert((await frame.locator('#chop-status').textContent()).includes('Slice 1'));
 await frame.locator('#chop-crossfade').fill('100');
 await frame.locator('#chop-crossfade').dispatchEvent('input');
 assert.equal(await frame.locator('#chop-mix-value').textContent(),'Chops only');
 await page.waitForTimeout(500);
 assert(await energy()<.0001,'Right endpoint mutes beat after slice ends');
 await frame.locator('[data-pad="4"]').click();
 await page.waitForTimeout(80);
 const slicePeak=await energy();assert(slicePeak>.001,'Pad produces actual audio');
 await frame.locator('#chop-repeat').selectOption('4');
 await frame.locator('[data-pad="1"]').focus();
 await page.keyboard.down('2');await page.waitForTimeout(650);
 const repeatedAt=await frame.locator('#flow-chop-demo').getAttribute('data-last-pad-time');
 await page.keyboard.up('2');await page.waitForTimeout(250);
 const releasedAt=await frame.locator('#flow-chop-demo').getAttribute('data-last-pad-time');
 await page.waitForTimeout(250);
 assert.equal(await frame.locator('#flow-chop-demo').getAttribute('data-last-pad-time'),releasedAt,'Release ends repeats');
 await frame.locator('#chop-stop').click();await page.waitForTimeout(100);assert(await energy()<.0001,'Stop all silences graph');
 await frame.locator('#chop-demo-play').click();await page.waitForTimeout(1200);
 assert((await frame.locator('#chop-status').textContent()).startsWith('Demo'));
 await frame.locator('#chop-stop').click();
 const layouts=[];
 for(const width of [800,390,320]){await page.setViewportSize({width,height:900});await page.waitForTimeout(100);layouts.push(await f.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,pads:[...document.querySelectorAll('[data-pad]')].map(e=>({w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height}))})));assert(layouts.at(-1).scroll<=layouts.at(-1).width,'No horizontal overflow');}
 await page.setViewportSize({width:800,height:780});await page.waitForTimeout(100);await page.screenshot({path:path.join(output,'preview-tested.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 const report={passed:true,checks:['Audio decoded','Beat audible','Pad audible','Crossfader endpoints','Keyboard hold repeat and release','Stop all silences','Automatic demo runs','No JS errors','Responsive layouts'],backingPeak,slicePeak,repeatedAt,releasedAt,layouts};
 fs.writeFileSync(path.join(output,'browser-validation.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
