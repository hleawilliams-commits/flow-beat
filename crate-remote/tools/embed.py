"""ui/index.html -> ui_html.h (one C string). Run after editing the page."""
from pathlib import Path
here = Path(__file__).resolve().parents[1]
html = (here / "ui/index.html").read_bytes()
out = ["/* Generated by tools/embed.py from ui/index.html. Do not edit. */",
       "#ifndef CR_UI_HTML_H", "#define CR_UI_HTML_H", "static const char CR_UI_HTML[] ="]
for i in range(0, len(html), 96):
    chunk = html[i:i + 96]
    s = "".join(chr(b) if 32 <= b < 127 and b not in (34, 92, 63) else f"\\{b:03o}" for b in chunk)
    out.append(f'    "{s}"')
out[-1] += ";"
out.append("#endif")
(here / "ui_html.h").write_text("\n".join(out) + "\n")
print(f"ui_html.h: {len(html)} bytes")
